package ru.spbstu.mdp.world;

/** Тип клетки мира. */
public enum CellType {
    /** Обычная клетка: агент получает R(s) и продолжает движение. */
    EMPTY,
    /** Препятствие: войти нельзя, агент, «ударившись», остаётся на месте. */
    WALL,
    /** Конечное состояние (+1 / −1): эпизод завершается. */
    TERMINAL
}
